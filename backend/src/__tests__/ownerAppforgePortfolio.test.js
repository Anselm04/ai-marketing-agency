import request from 'supertest';
import app from '../index.js';
import store from '../utils/store.js';
import { signEcosystemPayload } from '../services/ecosystemSignature.js';
import { canonicalOwnerEmail } from '../utils/owner.js';

const SECRET = 'personal-portfolio-test-secret';

function signedPost(body) {
  process.env.TRILLION_ECOSYSTEM_SHARED_SECRET = SECRET;
  const timestamp = String(Date.now());
  const signature = signEcosystemPayload(SECRET, timestamp, JSON.stringify(body));
  return request(app)
    .post('/api/integrations/appforge/campaign')
    .set('X-Trillion-Source', 'appforge')
    .set('X-Trillion-Timestamp', timestamp)
    .set('X-Trillion-Signature', signature)
    .send(body);
}

async function ensureUser(email, password = 'PortfolioTest123!') {
  const existing = await store.findUserByEmail(email);
  if (existing) return existing;
  await store.createUser({
    email,
    password,
    role: 'user',
    profile: { firstName: 'Portfolio', lastName: 'User' },
  });
  return store.findUserByEmail(email);
}

function appforgeBody({ email, projectId, mode = 'draft', name = 'Portfolio Product' }) {
  return {
    source: 'appforge',
    sourceProjectId: projectId,
    sourceProjectCreatedAt: new Date().toISOString(),
    sourceUserEmail: email,
    sourceUserName: 'AppForge User',
    productName: name,
    description: 'A product generated by AppForge for this users own Marketing portfolio.',
    techStack: 'React, Node',
    productUrl: 'https://example.com/product-' + projectId,
    mode,
  };
}

describe('Personal AppForge portfolio and Marketing entitlement', () => {
  beforeAll(async () => {
    await ensureUser(canonicalOwnerEmail(), 'OwnerSecurePass123!');
  });

  test('owner products retain permanent Marketing access without a paid subscription', async () => {
    const projectId = 810000000 + Math.floor(Math.random() * 1000000);
    const body = appforgeBody({
      email: canonicalOwnerEmail(),
      projectId,
      mode: 'draft',
      name: 'Owner Portfolio Product',
    });

    const res = await signedPost(body);

    expect(res.status).toBe(201);
    expect(res.body.portfolioAdded).toBe(true);
    expect(res.body.portfolioProduct).toEqual(expect.objectContaining({
      sourceProjectId: projectId,
      ownerOnly: true,
      autoMarketingEligible: true,
    }));
    expect(res.body.entitlement).toEqual(expect.objectContaining({
      reason: 'owner_access',
      source: 'owner',
    }));
    expect(res.body.campaign).toEqual(expect.objectContaining({
      sourceProjectId: projectId,
      appforgePortfolioProduct: true,
      status: 'draft',
    }));
  });

  test('unpaid users get their own AppForge product in their portfolio but cannot market it yet', async () => {
    const email = 'unpaid-appforge-' + Date.now() + '@example.com';
    const user = await ensureUser(email);
    const projectId = 820000000 + Math.floor(Math.random() * 1000000);
    const body = appforgeBody({
      email,
      projectId,
      mode: 'generate',
      name: 'Unpaid User Product',
    });

    const res = await signedPost(body);

    expect(res.status).toBe(402);
    expect(res.body.portfolioAdded).toBe(true);
    expect(res.body.automatedMarketing).toBe(false);
    expect(res.body.code).toBe('marketing_entitlement_required');
    expect(res.body.portfolioProduct).toEqual(expect.objectContaining({
      ownerId: user.id,
      sourceProjectId: projectId,
      ownerOnly: false,
      autoMarketingEligible: false,
      marketingStatus: 'payment_required',
    }));

    const campaigns = await store.getCampaignsByOwner(user.id);
    expect(campaigns.some((campaign) => campaign.sourceProjectId === projectId)).toBe(false);
  });

  test('a plan god-code entitlement unlocks Marketing for that users own AppForge portfolio only', async () => {
    const email = 'godcode-appforge-' + Date.now() + '@example.com';
    const user = await ensureUser(email);
    await store.createSubscription({
      userId: user.id,
      user: user.id,
      plan: 'growth',
      status: 'active',
      source: 'god-code',
      godGrant: 'growth',
      lifetimeAccess: true,
      expiresAt: null,
    });

    const projectId = 830000000 + Math.floor(Math.random() * 1000000);
    const res = await signedPost(appforgeBody({
      email,
      projectId,
      mode: 'draft',
      name: 'God Code User Product',
    }));

    expect(res.status).toBe(201);
    expect(res.body.portfolioProduct.ownerId).toBe(user.id);
    expect(res.body.portfolioProduct.autoMarketingEligible).toBe(true);
    expect(res.body.entitlement).toEqual(expect.objectContaining({
      reason: 'god_code',
      source: 'god-code',
      plan: 'growth',
    }));
    expect(res.body.campaign.owner).toBe(user.id);

    const owner = await store.findUserByEmail(canonicalOwnerEmail());
    const ownerCampaigns = await store.getCampaignsByOwner(owner.id);
    expect(ownerCampaigns.some((campaign) => campaign.sourceProjectId === projectId)).toBe(false);
  });

  test('a paid subscription unlocks Marketing for that users own AppForge portfolio only', async () => {
    const email = 'paid-appforge-' + Date.now() + '@example.com';
    const user = await ensureUser(email);
    await store.createSubscription({
      userId: user.id,
      user: user.id,
      plan: 'starter',
      status: 'active',
      source: 'stripe',
      lookup_key: 'marketing_starter_monthly',
      lifetimeAccess: false,
      expiresAt: null,
    });

    const projectId = 840000000 + Math.floor(Math.random() * 1000000);
    const res = await signedPost(appforgeBody({
      email,
      projectId,
      mode: 'draft',
      name: 'Paid User Product',
    }));

    expect(res.status).toBe(201);
    expect(res.body.portfolioProduct.ownerId).toBe(user.id);
    expect(res.body.entitlement).toEqual(expect.objectContaining({
      reason: 'paid_subscription',
      source: 'stripe',
      plan: 'starter',
    }));
    expect(res.body.campaign.owner).toBe(user.id);
  });

  test('AppForge product intake requires a matching Marketing account', async () => {
    const projectId = 850000000 + Math.floor(Math.random() * 1000000);
    const res = await signedPost(appforgeBody({
      email: 'no-marketing-account-' + Date.now() + '@example.com',
      projectId,
      mode: 'draft',
    }));

    expect(res.status).toBe(409);
    expect(res.body.code).toBe('marketing_account_required');
  });
});
